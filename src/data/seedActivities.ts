// Helper to generate reliable aesthetic SVG data URIs for mountains and outdoor activities
function createMountainSvg(title: string, subtitle: string, peakM: number, colorTheme: 'granite' | 'sunset' | 'winter' | 'autumn' | 'emerald' | 'crimson'): string {
  const themes = {
    granite: { bg1: '#1c1917', bg2: '#292524', peak1: '#78716c', peak2: '#a8a29e', sky: '#44403c', accent: '#fbbf24' },
    sunset: { bg1: '#2e1065', bg2: '#4c1d95', peak1: '#b45309', peak2: '#f59e0b', sky: '#831843', accent: '#f43f5e' },
    winter: { bg1: '#0f172a', bg2: '#1e293b', peak1: '#94a3b8', peak2: '#e2e8f0', sky: '#334155', accent: '#38bdf8' },
    autumn: { bg1: '#451a03', bg2: '#78350f', peak1: '#b45309', peak2: '#d97706', sky: '#9a3412', accent: '#f97316' },
    emerald: { bg1: '#064e3b', bg2: '#065f46', peak1: '#047857', peak2: '#34d399', sky: '#022c22', accent: '#10b981' },
    crimson: { bg1: '#3b0764', bg2: '#581c87', peak1: '#991b1b', peak2: '#ef4444', sky: '#4c0519', accent: '#fb7185' },
  };

  const t = themes[colorTheme];

  const escapeXml = (str: string) =>
    str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

  const safeTitle = escapeXml(title);
  const safeSubtitle = escapeXml(subtitle);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="800" height="600">
    <defs>
      <linearGradient id="sky-${colorTheme}" x1="0%" y1="0%" x2="0%" y2="100%">
        <stop offset="0%" stop-color="${t.bg1}"/>
        <stop offset="60%" stop-color="${t.sky}"/>
        <stop offset="100%" stop-color="${t.bg2}"/>
      </linearGradient>
      <linearGradient id="peak-${colorTheme}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${t.peak1}"/>
        <stop offset="100%" stop-color="${t.peak2}"/>
      </linearGradient>
    </defs>
    <rect width="800" height="600" fill="url(#sky-${colorTheme})"/>
    <circle cx="620" cy="180" r="45" fill="${t.accent}" opacity="0.4"/>
    <path d="M50 600 L260 220 L420 600 Z" fill="${t.bg2}" opacity="0.8"/>
    <path d="M220 600 L480 140 L700 600 Z" fill="url(#peak-${colorTheme})"/>
    <path d="M480 140 L540 240 L450 260 Z" fill="#ffffff" opacity="0.25"/>
    <path d="M420 600 L640 280 L800 600 Z" fill="${t.bg1}" opacity="0.9"/>
    <rect x="0" y="480" width="800" height="120" fill="#0c0a09" opacity="0.85"/>
    <text x="48" y="525" fill="#f5f5f4" font-family="system-ui, -apple-system, sans-serif" font-size="28" font-weight="700">${safeTitle}</text>
    <text x="48" y="558" fill="#a8a29e" font-family="system-ui, -apple-system, sans-serif" font-size="16">${safeSubtitle} · ${peakM}m</text>
  </svg>`;

  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

